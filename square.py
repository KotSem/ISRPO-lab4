def area(a):
    '''
    Принимает сторону квадрата a (int / float).
    Возвращает площадь квадрата (int / float): S = a**2.
    Пример вызова: area(5) -> 25
    '''
    return a * a


def perimeter(a):
    '''
    Принимает сторону квадрата a (int / float).
    Возвращает периметр квадрата (int / float): P = 4 * a.
    Пример вызова: perimeter(5) -> 20
    '''
    return 4 * a
