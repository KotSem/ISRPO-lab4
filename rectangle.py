def area(a, b):
    '''
    Принимает стороны прямоугольника a и b (int / float).
    Возвращает площадь прямоугольника (int / float): S = a * b.
    Пример вызова: area(3, 4) -> 12
    '''
    return a * b


def perimeter(a, b):
    '''
    Принимает стороны прямоугольника a и b (int / float).
    Возвращает периметр прямоугольника (int / float): P = 2 * (a + b).
    Пример вызова: perimeter(3, 4) -> 14
    '''
    return 2 * (a + b)
